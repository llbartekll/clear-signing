#!/usr/bin/env python3
"""Generate crates/clear-signing/src/native_currencies.rs from the EIP-155 chain list.

Usage: scripts/generate_native_currencies.py [path/to/chains_mini.json]

Without an argument, the script downloads https://chainid.network/chains_mini.json.
"""

import json
import pathlib
import sys
import urllib.request

SOURCE_URL = "https://chainid.network/chains_mini.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/clear-signing/src/native_currencies.rs"


def rust_str(value: str) -> str:
    escaped = []
    for ch in value:
        if ch in ('"', "\\"):
            escaped.append("\\" + ch)
        elif ord(ch) < 0x20:
            escaped.append(f"\\u{{{ord(ch):x}}}")
        else:
            escaped.append(ch)
    return '"' + "".join(escaped) + '"'


def main() -> None:
    if len(sys.argv) > 1:
        chains = json.loads(pathlib.Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(SOURCE_URL) as resp:
            chains = json.load(resp)

    rows = {}
    for chain in chains:
        native = chain.get("nativeCurrency") or {}
        if not all(k in native for k in ("symbol", "name", "decimals")):
            continue
        rows[int(chain["chainId"])] = (native["symbol"], native["name"], int(native["decimals"]))

    lines = [
        "// @generated by scripts/generate_native_currencies.py from",
        f"// {SOURCE_URL}. Do not edit by hand.",
        "",
        "/// `(chain_id, symbol, name, decimals)`, sorted by `chain_id`.",
        "pub(crate) static NATIVE_CURRENCIES: &[(u64, &str, &str, u8)] = &[",
    ]
    for chain_id in sorted(rows):
        symbol, name, decimals = rows[chain_id]
        lines.append(f"    ({chain_id}, {rust_str(symbol)}, {rust_str(name)}, {decimals}),")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(rows)} chains to {OUT}")


if __name__ == "__main__":
    main()
