#!/usr/bin/env python3
"""Generate crates/clear-signing/src/chain_names.rs from the EIP-155 chain list.

Usage: scripts/generate_chain_names.py [path/to/chains.json]

Without an argument, the script downloads https://chainid.network/chains.json.
"""

import json
import pathlib
import sys
import urllib.request

SOURCE_URL = "https://chainid.network/chains.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/clear-signing/src/chain_names.rs"


def rust_str(value: str) -> str:
    escaped = []
    for ch in value:
        if ch in ('"', "\\"):
            escaped.append("\\" + ch)
        elif ord(ch) < 0x20:
            escaped.append(f"\\u{{{ord(ch):x}}}")
        else:
            escaped.append(ch)
    return '"' + "".join(escaped) + '"'


def main() -> None:
    if len(sys.argv) > 1:
        chains = json.loads(pathlib.Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(SOURCE_URL) as resp:
            chains = json.load(resp)

    rows = {}
    for chain in chains:
        name = chain.get("name")
        if not isinstance(name, str) or not name:
            continue
        rows[int(chain["chainId"])] = name

    lines = [
        "// @generated by scripts/generate_chain_names.py from",
        f"// {SOURCE_URL}. Do not edit by hand.",
        "",
        "/// `(chain_id, name)`, sorted by `chain_id`.",
        "pub(crate) static CHAIN_NAMES: &[(u64, &str)] = &[",
    ]
    for chain_id in sorted(rows):
        lines.append(f"    ({chain_id}, {rust_str(rows[chain_id])}),")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(rows)} chains to {OUT}")


if __name__ == "__main__":
    main()
